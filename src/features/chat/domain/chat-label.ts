import { messageText } from "@/lib/ai/reply";
import type { ChatUIMessage } from "@/features/chat/types";

const MAX_LABEL_LENGTH = 40;

const MAX_GENERATED_TITLE_LENGTH = 60;

/** `text` on one line, cut at a word to at most `max` characters plus "…". */
function shortenAtWord(text: string, max: number): string {
  const line = text.replace(/\s+/g, " ").trim();
  if (line.length <= max) return line;

  const head = line.slice(0, max + 1);
  const wordEnd = head.lastIndexOf(" ");
  const cut =
    wordEnd > 0
      ? head.slice(0, wordEnd)
      : withoutHalfCharacter(head.slice(0, max));
  return `${cut.replace(/[\s,;:.-]+$/, "")}…`;
}

/**
 * `text` without a trailing high surrogate, the first half of a character
 * a cut went through, which shows as a broken glyph and which the database
 * refuses to store.
 */
function withoutHalfCharacter(text: string): string {
  return /[\uD800-\uDBFF]$/.test(text) ? text.slice(0, -1) : text;
}

/**
 * What a message is about, in words: its text, or for a message of only
 * attached Materials, the first Material's name.
 */
export function messageGist(parts: ChatUIMessage["parts"]): string {
  const text = messageText(parts);
  if (text.trim() !== "") return text;
  const material = parts.find((part) => part.type === "data-material");
  return material?.data.name ?? "";
}

/**
 * How a Chat is named in the Chat list: its title, or until it has one, its
 * first message on one line, shortened at a word (`messageGist`).
 */
export function chatLabel({
  title,
  firstMessage,
}: {
  title: string | null;
  firstMessage: ChatUIMessage["parts"] | null;
}): string {
  if (title?.trim()) return title.trim();

  const text = shortenAtWord(
    firstMessage ? messageGist(firstMessage) : "",
    MAX_LABEL_LENGTH,
  );
  return text === "" ? "New chat" : text;
}

/**
 * A title generated by the AI as the Chat's title: its first line without
 * quotes or Markdown, shortened at a word. Null when nothing is left.
 */
export function generatedTitle(text: string): string | null {
  const firstLine = text
    .split("\n")
    .map((line) => line.replace(/^[\s#*_"'“”‘’`]+|[\s*_"'“”‘’`.]+$/g, ""))
    .find((line) => line !== "");
  return firstLine
    ? shortenAtWord(firstLine, MAX_GENERATED_TITLE_LENGTH)
    : null;
}
